# while loop is used to execute a block of code repeatedly until a condition is met.

# syntax:
# while condition:
#     body of the loop

# ----------------------------------------------------------------

# example:

i = 1
while i <= 10:
    print(i)
    i += 1

# ----------------------------------------------------------------

# An example program to print "Hello World" 5 times

i = 1
while i <= 5:
    print("Hello World")
    i += 1

# ----------------------------------------------------------------

# An example program to print the sum of first 10 natural numbers

i = 1
sum = 0
while i <= 10:
    sum += i # sum = sum + i
    i += 1

print(sum)


# Precedence of Arithmetic Operators

# + and - have the same precedence
# * and / have the same precedence
# ** has the highest precedence

# Precedence of Arithmetic Operators

print(5+2*3)          # 11

print(5+2**3)          # 13

print(5+2*3**2)          # 23

print(5+2*3**2)          # 23

# ------------------------------------------------------------

# Associativity of Arithmetic Operators

# + and - have left associativity
# * and / have left associativity
# ** has right associativity

print(5+2-3)          # 4
print(2**2**-1)          # 2
print((2**2)**-1)          # 0.25


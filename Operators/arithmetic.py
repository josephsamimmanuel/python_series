# Arithmetic Operators in Python

# Addition
# Subtraction
# Multiplication
# Division
# Modulus
# Exponentiation
# Floor Division

# Addition
a = 10
b = 20
print(a + b)          # 30

# Subtraction
a = 10
b = 20
print(a - b)          # -10

# Multiplication
a = 10
b = 20
print(a * b)          # 200

# Division
a = 10
b = 20
print(a / b)          # 0.5

# Modulus
a = 10
b = 20
print(a % b)          # 10  

# Exponentiation
a = 10
b = 20
print(a ** b)          # 100000000000000000000

# Floor Division
a = 100
b = 20
print(a // b)          # 5


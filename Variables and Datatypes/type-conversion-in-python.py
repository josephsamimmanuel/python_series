# Type Conversion in Python

# Implicit Type Conversion

# Explicit Type Conversion

# ------------------------------------------------------------------------------------------------

# Implicit Type Conversion

a = 10
b = 20
c = a + b
print(c)            # 30


d = True
e = a + d
print(e)            # 11    

# ------------------------------------------------------------------------------------------------

# Explicit Type Conversion

s = "135"
i = 10 + int(s)
f = float(s)
print(i)            # 145
print(f)            # 135.0

# ------------------------------------------------------------------------------------------------  

x = "geeks"
print(list(x))            # ['g', 'e', 'e', 'k', 's']
print(tuple(x))           # ('g', 'e', 'e', 'k', 's')
print(set(x))             # {'g', 'e', 'k', 's'} distinct elements

# ------------------------------------------------------------------------------------------------

l = ['a', 'b', 'c']
print(str(l))            # ['a', 'b', 'c']

j = 10
k = 20
print(str(j) + str(k))   # 1020

l = 12.5
print(int(l))            # 12
# ------------------------------------------------------------------------------------------------

r = (10,20,30)
print(list(r))            # [10, 20, 30]

s = {10,20,30}
print(tuple(s))           # (10, 20, 30)

# ------------------------------------------------------------------------------------------------

n = 20

print(bin(n))            # 0b10100
print(oct(n))            # 0o24
print(hex(n))            # 0x14

# ------------------------------------------------------------------------------------------------

e = "1001"
print(int(e,2))            # 9

f = "1001"
print(int(f,8))            # 521

g = "14"
print(int(g,16))            # 20

